using System.Globalization;
using System.Text;
using FcaBedrock.Core.Spec;
using FcaBedrock.Spec.Toml;

namespace FcaBedrock.Discovery;

/// <summary>One attribute ready to author, in draft order.</summary>
/// <param name="Name">The final logical name, after any collision repair.</param>
/// <param name="Source">The selector, exactly as the naming matrix chose it.</param>
/// <param name="Domain">The observed domain.</param>
/// <param name="Omission">The CR/LF categories left out of a complete domain, or null when there are none.</param>
internal sealed record ProbedAttribute(string Name, SourceSection Source, RetainedDomain Domain, DomainOmission? Omission);

/// <summary>
/// Assembles the draft <see cref="SpecDocument"/>: the exact D-107 content inventory and
/// nothing else.
/// <para>
/// <b>What is deliberately absent, and why.</b> No schema or output fingerprint (a draft is a
/// starting point, never a frozen artifact; a stored hash would fossilize a schema the user has
/// not reviewed, §14); no <c>created_at</c>, tool version, path, or machine text (the no-clock
/// rule, D-079/EP-13) (and a clock would break byte repeatability outright, D-112); no
/// <c>[defaults]</c>, <c>[output]</c>, templates, matchers, or <c>[binding.object_key]</c> (the
/// defaults are already correct: a wide object key is <c>row_index</c>, and a triple object is
/// its subject). The caller may enrich the returned record afterwards (it is a public document
/// model), which is exactly why the probe API takes no provenance parameters (EP-6).
/// </para>
/// <para>
/// <b>Everything effective is authored explicitly</b>, including settings that equal their
/// defaults, so the draft documents the run that produced it rather than relying on the reader
/// to know §5.1 (D-107). Presence tracking means an omitted field is genuinely omitted: an
/// all-missing attribute writes no <c>declared_domain</c> at all, not <c>[]</c>. An authored
/// <c>[]</c> is a fixed empty domain that suppresses observed-domain calibration, so it would
/// misrepresent the observation as an authored empty domain (§7.1, §10.3, D-122). The one
/// attribute that authors <c>[]</c> is a complete one whose every category contains CR or LF:
/// its observed domain is not empty, but none of it can be saved.
/// </para>
/// <para>
/// <b>Omissions are saved, not only reported.</b> A draft that leaves categories out says so in
/// the first line of <c>[provenance].notes</c> and in each affected attribute's
/// <c>description</c>, so a reader of the file learns it without the probe's warnings. Both are
/// free text, so neither changes a fingerprint (§14). A draft with no omission keeps exactly
/// the notes and descriptions it had before omissions existed.
/// </para>
/// </summary>
internal static class ProbeDraft
{
    /// <summary>The deterministic <c>[spec].description</c> of every probe draft (D-107).</summary>
    public const string Description = "Draft spec generated by probe.";

    /// <summary>
    /// Builds the draft over <paramref name="binding"/>, one attribute per entry of
    /// <paramref name="attributes"/>, in order, checking cancellation before each attribute. A
    /// triple draft passes the binding the role-map preflight already validated: the same
    /// instance, so what was checked and what is authored cannot drift.
    /// </summary>
    public static SpecDocument Build(
        BindingSection binding,
        ProbeOptions options,
        IReadOnlyList<ProbedAttribute> attributes,
        CancellationToken cancellationToken)
    {
        var sections = new List<AttributeSection>(attributes.Count);
        var truncated = 0;
        var omittedAttributes = 0;
        var omittedCategories = 0L;
        foreach (var attribute in attributes)
        {
            cancellationToken.ThrowIfCancellationRequested();
            sections.Add(Attribute(attribute, options.ValueRetentionLimit));
            if (attribute.Domain.Truncated)
            {
                truncated++;
            }

            if (attribute.Omission is { } omission)
            {
                omittedAttributes++;
                omittedCategories = checked(omittedCategories + omission.Omitted);
            }
        }

        var notes = Notes(options.ValueRetentionLimit, truncated);
        if (omittedAttributes > 0)
        {
            notes = OmissionNotes(omittedCategories, omittedAttributes) + "\n" + notes;
        }

        return Document(binding, notes, sections);
    }

    /// <summary>
    /// The <c>[binding]</c> of a wide draft: every effective read setting explicitly authored,
    /// and no ordering or role map, which the wide shape does not have (§5.2, §7.1).
    /// </summary>
    public static BindingSection WideBinding(SourceReadSettings readSettings, ProbeOptions options) =>
        new(
            Shape: readSettings.Shape,
            Encoding: readSettings.Encoding,
            Delimiter: readSettings.Delimiter,
            QuoteChar: readSettings.QuoteChar,
            HasHeader: readSettings.HasHeader,
            Locale: options.Locale,
            MissingToken: readSettings.MissingToken,
            Ordering: null,
            Columns: null,
            ObjectKey: null);

    /// <summary>
    /// The selector the wide naming matrix chose for <paramref name="column"/>: a unique usable
    /// header binds by name, everything else by physical index.
    /// </summary>
    public static SourceSection ColumnSource(DiscoveredColumn column) =>
        column.BindByName is { } headerName
            ? new ColumnSourceSection(Index: null, Name: headerName, ValueType: SourceValueType.String)
            : new ColumnSourceSection(Index: column.Index, Name: null, ValueType: SourceValueType.String);

    /// <summary>
    /// The selector of a triple attribute: the EXACT predicate text, always. A triple selector is
    /// the string the data spells, so rewriting it would point the attribute at a predicate that
    /// does not exist (§7.1). When the name had to be synthesized, only the name moved.
    /// </summary>
    public static SourceSection PredicateSource(DiscoveredPredicate predicate) =>
        new PredicateSourceSection(Name: predicate.Predicate, ValueType: SourceValueType.String);

    /// <summary>
    /// The binding-only document the triple role-map preflight resolves: the exact
    /// <c>[binding]</c> the draft will author, and no attributes at all.
    /// <para>
    /// Discovery deliberately duplicates none of §5.3's validation. Before a single row is read,
    /// it hands the authored binding to the one owner of those rules,
    /// <c>SpecResolver.ResolveBinding</c>, which resolves the binding alone (D-135). An invalid
    /// role map therefore fails with the <em>same</em> <c>spec validate</c> diagnostics a user
    /// would see from <c>validate</c>, forwarded rather than re-emitted (D-067). The preflight
    /// doubles as up-front proof of the D-107 resolve leg for the binding half of the draft.
    /// </para>
    /// </summary>
    public static SpecDocument BindingOnly(BindingSection binding) =>
        Document(binding, notes: null, attributes: []);

    /// <summary>
    /// The shared document shell: the D-107 inventory's fixed parts. <paramref name="notes"/>
    /// is null only for the preflight document, which is never returned to a caller and so needs
    /// no provenance notes.
    /// </summary>
    private static SpecDocument Document(
        BindingSection binding,
        string? notes,
        IReadOnlyList<AttributeSection> attributes) =>
        new(
            Spec: new SpecSection(
                Version: 1,
                SchemaFingerprint: null,
                CxtOutputFingerprint: null,
                DatOutputFingerprint: null,
                Extends: null,
                Description: Description),
            Provenance: notes is null
                ? null
                : new ProvenanceSection(
                    Author: null,
                    CreatedAt: null,
                    SourceUrl: null,
                    SourceHash: null,
                    DerivedFrom: null,
                    Notes: notes),
            Binding: binding,
            Defaults: null,
            Output: null,
            Templates: [],
            Matchers: [],
            Attributes: attributes);

    /// <summary>
    /// The <c>[binding]</c> of a triple draft: every effective read setting explicitly authored,
    /// plus the caller's role map in the caller's own addressing mode.
    /// <para>
    /// <b>The role map is authored as supplied, not as resolved.</b> A name-addressed map stays
    /// name-addressed and an index-addressed one stays index-addressed, spelled exactly as the
    /// caller wrote it; the resolved indices are read machinery for this one pass, not a rewrite
    /// of the document. An omitted map is not "absent" in the draft; it is authored
    /// explicitly as 0/1/2, because a self-documenting draft states what it read (D-107).
    /// </para>
    /// <para>
    /// <c>ordering</c> is whatever the caller selected, never inferred from the data:
    /// <c>subject_grouped</c> is explicit-only (§7.1), so observing contiguous subjects must not
    /// promote an <c>unordered</c> probe. No <c>[binding.object_key]</c> is authored: the triple
    /// default is already the subject.
    /// </para>
    /// </summary>
    public static BindingSection TripleBinding(
        SourceReadSettings readSettings, ProbeOptions options, TripleColumnsSection columns) =>
        new(
            Shape: readSettings.Shape,
            Encoding: readSettings.Encoding,
            Delimiter: readSettings.Delimiter,
            QuoteChar: readSettings.QuoteChar,
            HasHeader: readSettings.HasHeader,
            Locale: options.Locale,
            MissingToken: readSettings.MissingToken,
            Ordering: readSettings.Ordering,
            Columns: columns,
            ObjectKey: null);

    /// <summary>
    /// The always-written <c>[provenance].notes</c> (D-108), written even at zero truncations,
    /// so every draft explains which limit produced it rather than leaving a reader to guess
    /// whether a complete-looking domain is complete.
    /// </summary>
    public static string Notes(int limit, int truncatedCount) =>
        string.Create(
            CultureInfo.InvariantCulture,
            $"probe: per-attribute retention limit {limit}; truncated attributes: {truncatedCount}.");

    /// <summary>
    /// The truncation marker a truncated attribute carries in its <c>description</c> (D-108,
    /// verbatim from the §7.1 example). Human-readable by design: the strict reader rejects
    /// unknown keys, so there is no machine-readable truncation field to add (D-075).
    /// </summary>
    public static string TruncationMarker(int limit) =>
        string.Create(
            CultureInfo.InvariantCulture,
            $"probe: domain truncated after {limit} distinct values; more exist.");

    /// <summary>
    /// The first line of <c>[provenance].notes</c> when any category was omitted: the
    /// file-wide summary that leads the notes, before the retention line. The counts are
    /// distinct categories per attribute, summed, and the attributes they came from.
    /// </summary>
    public static string OmissionNotes(long omittedCategories, int attributes) =>
        string.Create(
            CultureInfo.InvariantCulture,
            $"probe: WARNING: omitted {omittedCategories} distinct categories containing CR/LF across {attributes} attributes (counts are per attribute). These categories produce no crosses; objects are kept. Review the affected attribute descriptions.");

    /// <summary>
    /// The <c>description</c> of an attribute that omitted categories: how many it left out and
    /// kept, up to three samples of what it left out, and for an all-unsafe attribute what its
    /// authored empty domain means. Every part is bounded (<see cref="ProbeSample"/>), so the
    /// whole stays within 3,072 UTF-16 code units without being cut.
    /// </summary>
    public static string OmissionDescription(DomainOmission omission)
    {
        var builder = new StringBuilder();
        builder.Append(
            CultureInfo.InvariantCulture,
            $"probe: omitted {omission.Omitted} distinct categories containing CR/LF; retained {omission.Kept.Count} representable categories. Omitted examples: ");
        for (var i = 0; i < omission.Sample.Count; i++)
        {
            if (i > 0)
            {
                builder.Append(", ");
            }

            builder.Append(ProbeSample.Format(omission.Sample[i]));
        }

        builder.Append('.');
        if (omission.Kept.Count == 0)
        {
            builder.Append(" The declared domain is fixed empty; unknown values warn.");
        }

        return builder.ToString();
    }

    // One attribute, shared by both shapes: they differ only in which selector carrier addresses
    // the source, so everything else (the explicit value_type, identity + nominal, the domain,
    // and the truncation pair) is authored identically. That symmetry is a requirement, not a
    // convenience (D-106), so it is structural here rather than maintained in two places.
    private static AttributeSection Attribute(ProbedAttribute attribute, int limit) =>
        attribute.Omission is { } omission
            ? Omitting(attribute, omission)
            : Observed(attribute.Name, attribute.Source, attribute.Domain, limit);

    // A complete domain with CR/LF categories: the representable ones in first-observation order,
    // or an authored [] when there are none, and an explicit `warn`. The policy is already the
    // default, but authored here so a later edit to [defaults] cannot quietly turn the omitted
    // categories into a `fail` (§10.6). Never a truncated domain: that yields no draft.
    private static AttributeSection Omitting(ProbedAttribute attribute, DomainOmission omission) =>
        new(
            Name: attribute.Name,
            Source: attribute.Source,
            Description: OmissionDescription(omission),
            Include: null,
            Template: null,
            Discretizer: new IdentityDiscretizerSection(),
            Scale: new NominalScaleSection(),
            DeclaredDomain: omission.Kept,
            RestrictTo: null,
            ValueLabels: null,
            MissingPolicy: null,
            UnknownValuePolicy: UnknownValuePolicy.Warn);

    private static AttributeSection Observed(string name, SourceSection source, RetainedDomain domain, int limit) =>
        new(
            Name: name,
            // An EXPLICIT value_type: probe authors no typing, and `string` is the only type
            // `identity` accepts (§10.2, D-061), but writing it keeps the draft self-documenting
            // rather than default-dependent.
            Source: source,
            Description: domain.Truncated ? TruncationMarker(limit) : null,
            Include: null,
            Template: null,
            Discretizer: new IdentityDiscretizerSection(),
            Scale: new NominalScaleSection(),
            // An all-missing attribute is real and is authored; only its domain is unknown, so
            // the domain is omitted and the Calibrate phase fills it from the data (§10.3).
            // Omitted, not `[]`: an authored `[]` is a fixed empty domain that suppresses
            // observed-domain calibration (§10.3, D-122).
            DeclaredDomain: domain.Values.Count == 0 ? null : domain.Values,
            RestrictTo: null,
            ValueLabels: null,
            MissingPolicy: null,
            // The recovery half of D-108: a truncated prefix plus `include` lets a conversion of
            // this draft over the probed source re-append the tail in first-observation order
            // (§10.6/§17 rule 3), so the truncated draft and an untruncated one converge on the
            // same column set and order.
            UnknownValuePolicy: domain.Truncated ? UnknownValuePolicy.Include : null);
}
